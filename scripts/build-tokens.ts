import tokens from '../design/tokens.json';
function colors(theme: 'light' | 'dark') {
  return [
    ...Object.entries(tokens.color).map(([k, v]) => `  --m-${k}: ${v[theme]};`),
    ...tokens.data.categorical[theme].map(
      (v, i) => `  --m-data-${i + 1}: ${v};`,
    ),
    ...tokens.data.sequential[theme].map((v, i) => `  --m-seq-${i + 1}: ${v};`),
    `  --m-muted: ${tokens.data.muted[theme]};`,
  ].join('\n');
}
const stage = Object.entries(tokens.stage)
  .filter(([k]) => !k.startsWith('$'))
  .flatMap(([name, v]) =>
    typeof v === 'string'
      ? []
      : Object.entries(v).map(([part, value]) => `  --m-stage-${name}-${part}: ${value};`),
  )
  .join('\n');
const motion = [
  ...Object.entries(tokens.motion.duration).map(([k, v]) => `  --m-duration-${k}: ${v};`),
  ...Object.entries(tokens.motion.ease).map(([k, v]) => `  --m-ease-${k}: ${v};`),
].join('\n');
const sizes = Object.entries(tokens.size)
  .filter(([k]) => !k.startsWith('$'))
  .map(([k, v]) => `  --m-size-${k}: ${v};`)
  .join('\n');
await Bun.write(
  'web/src/styles/tokens.css',
  `/* Generated by bun run tokens. Edit design/tokens.json. */\n:root {\n${colors('light')}\n${sizes}\n${stage}\n${motion}\n}\n[data-theme="dark"] {\n${colors('dark')}\n color-scheme: dark;\n}\n@media (prefers-color-scheme: dark) { [data-theme="auto"] {\n${colors('dark')}\n color-scheme: dark;\n} }\n`,
);
await Bun.write(
  'web/public/favicon.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><style>:root{--ink:${tokens.color.ink.light};--paper:${tokens.color.bg.light};--line:${tokens.color['line-strong'].light};--lamp:${tokens.color.accent.light}}@media(prefers-color-scheme:dark){:root{--ink:${tokens.color.ink.dark};--paper:${tokens.color.bg.dark};--line:${tokens.color['line-strong'].dark}}}</style><circle cx="16" cy="16" r="15" fill="var(--paper)" stroke="var(--ink)"/><circle cx="16" cy="16" r="10" fill="none" stroke="var(--line)"/><path d="M 1 16 A 15 15 0 0 1 5.4 5.4" fill="none" stroke="var(--lamp)" stroke-width="3" stroke-linecap="round"/></svg>`,
);
